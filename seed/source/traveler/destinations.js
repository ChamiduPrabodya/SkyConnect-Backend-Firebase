function priceLevelFor(activity) {
  if (activity.priceLevel) return activity.priceLevel;
  const price = Number(activity.price) || 0;
  if (!price) {
    const text = `${activity.id || ''} ${activity.name || ''} ${activity.category || ''}`.toLowerCase();
    if (/safari|whale|dolphin|rafting|kite surf|surf lesson/.test(text)) return 'high';
    if (/snorkel|boat|cruise|train ride|guided tour|cycling|elephant/.test(text)) return 'moderate';
    if (/beach|walk|viewpoint|sunset|temple|church|kovil|market|stroll/.test(text)) return 'low';
    return 'moderate';
  }
  if (price <= 1500) return 'low';
  if (price <= 5000) return 'moderate';
  if (price <= 10000) return 'high';
  return 'premium';
}

function estimatedActivityPrice(activity) {
  const knownPrice = Number(activity.price);
  if (Number.isFinite(knownPrice) && knownPrice > 0) return knownPrice;
  const level = priceLevelFor(activity);
  return { low: 1200, moderate: 3500, high: 8500, premium: 15000 }[level] || 2500;
}

