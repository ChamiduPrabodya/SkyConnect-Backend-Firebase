const durationMinutes = (value) => {
  const text = String(value || '');
  const explicitValues = [...text.matchAll(/(\d+(?:\.\d+)?)\s*(min(?:ute)?s?|hr|hours?)/gi)];
  let values;
  if (explicitValues.length >= 2) {
    values = explicitValues.map(([, amount, unit]) =>
      Number(amount) * (/^min/i.test(unit) ? 1 : 60));
  } else {
    const numbers = text.match(/\d+(?:\.\d+)?/g)?.map(Number) || [1, 2];
    const factor = /min/i.test(text) && !/hr|hour/i.test(text) ? 1 : /day/i.test(text) ? 480 : 60;
    values = numbers.map((amount) => amount * factor);
  }
  return { min: Math.round(Math.min(...values)), max: Math.round(Math.max(...values)) };
};

